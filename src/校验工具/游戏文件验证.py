def get_base_dir() -> Path:
    """返回运行文件所在目录，而不是当前工作目录。"""
    if getattr(sys, "frozen", False):
        return Path(sys.executable).resolve().parent
    return Path(__file__).resolve().parent


def normalize_relpath(path: str) -> str:
    """统一相对路径格式，并按 Windows 语义进行大小写无关比较。"""
    path = path.replace("\\", "/").strip()
    while path.startswith("./"):
        path = path[2:]
    return path.casefold()


def load_manifest() -> dict[str, tuple[str, str]]:
    """
    返回:
        normalized_path -> (original_relative_path, expected_sha256)
    """
    blob = base64.b64decode(
        "".join(EMBEDDED_MANIFEST_GZIP_BASE64.split())
    )
    text = gzip.decompress(blob).decode("utf-8")

    reader = csv.DictReader(io.StringIO(text, newline=""))

    required = {"相对路径", "SHA256"}
    if not reader.fieldnames or not required.issubset(set(reader.fieldnames)):
        raise RuntimeError(
            "内嵌 SHA256 清单格式错误：缺少“相对路径”或“SHA256”列。"
        )

    manifest: dict[str, tuple[str, str]] = {}

    excluded = {normalize_relpath(p) for p in MANIFEST_EXCLUDED_PATHS}

    for row_no, row in enumerate(reader, start=2):
        rel = (row.get("相对路径") or "").strip()
        digest = (row.get("SHA256") or "").strip().lower()

        if not rel:
            raise RuntimeError(f"内嵌 SHA256 清单第 {row_no} 行路径为空。")

        if len(digest) != 64 or any(c not in "0123456789abcdef" for c in digest):
            raise RuntimeError(
                f"内嵌 SHA256 清单第 {row_no} 行 SHA256 无效：{digest!r}"
            )

        key = normalize_relpath(rel)

        if key in excluded:
            continue

        if key in manifest:
            raise RuntimeError(f"内嵌 SHA256 清单存在重复路径：{rel}")

        manifest[key] = (rel.replace("\\", "/"), digest)

    return manifest


def calc_sha256(path: Path) -> str:
    sha256 = hashlib.sha256()

    with path.open("rb") as f:
        while True:
            chunk = f.read(BUFFER_SIZE)
            if not chunk:
                break
            sha256.update(chunk)

    return sha256.hexdigest()


def is_runtime_tool_file(path: Path, base_dir: Path) -> bool:
    """判断文件是否属于校验器自身/辅助文件，应从目标版本比较中排除。"""
    try:
        rel = path.relative_to(base_dir)
    except ValueError:
        return False

    # 只对根目录工具文件做特殊排除，避免误排除子目录中同名的正常文件。
    if rel.parent != Path("."):
        return False

    name_cf = rel.name.casefold()

    if name_cf in RUNTIME_EXCLUDED_NAMES:
        return True

    # 排除当前运行的 EXE 或 .py 自身。
    try:
        if getattr(sys, "frozen", False):
            self_path = Path(sys.executable).resolve()
        else:
            self_path = Path(__file__).resolve()

        if path.resolve() == self_path:
            return True
    except OSError:
        pass

    return False


def collect_actual_files(base_dir: Path) -> dict[str, tuple[str, Path]]:
    """
    返回:
        normalized_path -> (original_relative_path, absolute_path)
    """
    actual: dict[str, tuple[str, Path]] = {}

    for path in base_dir.rglob("*"):
        if not path.is_file():
            continue

        if is_runtime_tool_file(path, base_dir):
            continue

        rel = path.relative_to(base_dir).as_posix()
        key = normalize_relpath(rel)
        actual[key] = (rel, path)

    return actual


def write_report(
    report_path: Path,
    base_dir: Path,
    manifest_count: int,
    actual_count: int,
    missing: list[str],
    mismatched: list[tuple[str, str, str]],
    extra: list[str],
    read_errors: list[tuple[str, str]],
) -> None:
    now = datetime.now().astimezone()

    lines: list[str] = []
    lines.append("CastleReforge 文件版本校验报告")
    lines.append("=" * 72)
    lines.append(f"时间：{now.strftime('%Y-%m-%d %H:%M:%S %z')}")
    lines.append(f"目录：{base_dir}")
    lines.append(f"目标文件数：{manifest_count}")
    lines.append(f"实际参与校验文件数：{actual_count}")
    lines.append("")

    total_errors = (
        len(missing)
        + len(mismatched)
        + len(extra)
        + len(read_errors)
    )

    if total_errors == 0:
        lines.append("结果：PASS")
        lines.append("所有目标文件均存在，SHA256 完全一致，且没有未登记文件。")
    else:
        lines.append("结果：FAIL")
        lines.append(f"错误总数：{total_errors}")
        lines.append("")

        if missing:
            lines.append(f"[缺失文件] {len(missing)}")
            for rel in missing:
                lines.append(f"  {rel}")
            lines.append("")

        if mismatched:
            lines.append(f"[SHA256 不符] {len(mismatched)}")
            for rel, expected, actual in mismatched:
                lines.append(f"  文件：{rel}")
                lines.append(f"  目标：{expected}")
                lines.append(f"  实际：{actual}")
                lines.append("")

        if extra:
            lines.append(f"[未登记的多余文件] {len(extra)}")
            for rel in extra:
                lines.append(f"  {rel}")
            lines.append("")

        if read_errors:
            lines.append(f"[读取失败] {len(read_errors)}")
            for rel, error in read_errors:
                lines.append(f"  文件：{rel}")
                lines.append(f"  错误：{error}")
                lines.append("")

    # UTF-8 BOM + CRLF，方便简体中文 Windows 直接用记事本查看。
    report_path.write_text(
        "\r\n".join(lines) + "\r\n",
        encoding="utf-8-sig",
        newline="",
    )


def show_message(title: str, text: str, is_error: bool) -> None:
    """Windows 下弹出结果框；失败时仍以 TXT 报告为准。"""
    if os.name != "nt":
        return

    try:
        import ctypes

        MB_OK = 0x00000000
        MB_ICONERROR = 0x00000010
        MB_ICONINFORMATION = 0x00000040

        flags = MB_OK | (MB_ICONERROR if is_error else MB_ICONINFORMATION)
        ctypes.windll.user32.MessageBoxW(None, text, title, flags)
    except Exception:
        pass


def main() -> int:
    base_dir = get_base_dir()
    report_path = base_dir / REPORT_NAME

    print("CastleReforge 文件版本校验器")
    print(f"校验目录：{base_dir}")
    print()

    try:
        manifest = load_manifest()
    except Exception as e:
        message = f"无法读取内嵌 SHA256 清单：{e}"

        try:
            report_path.write_text(
                "CastleReforge 文件版本校验报告\r\n"
                + "=" * 72
                + "\r\n结果：FAIL\r\n"
                + message
                + "\r\n",
                encoding="utf-8-sig",
                newline="",
            )
        except OSError:
            pass

        print(f"[FAIL] {message}")
        show_message(
            "CastleReforge 文件校验失败",
            f"{message}\n\n详细信息：{REPORT_NAME}",
            True,
        )
        return 2

    actual_files = collect_actual_files(base_dir)

    missing: list[str] = []
    mismatched: list[tuple[str, str, str]] = []
    extra: list[str] = []
    read_errors: list[tuple[str, str]] = []

    expected_keys = set(manifest)
    actual_keys = set(actual_files)

    # 缺失
    for key in sorted(expected_keys - actual_keys):
        rel, _expected_hash = manifest[key]
        missing.append(rel)

    # 多余
    for key in sorted(actual_keys - expected_keys):
        rel, _path = actual_files[key]
        extra.append(rel)

    # 共有文件：计算 SHA256
    common_keys = sorted(expected_keys & actual_keys)
    total = len(common_keys)

    for index, key in enumerate(common_keys, start=1):
        expected_rel, expected_hash = manifest[key]
        _actual_rel, path = actual_files[key]

        print(f"[{index}/{total}] {expected_rel}")

        try:
            actual_hash = calc_sha256(path)
        except OSError as e:
            read_errors.append((expected_rel, str(e)))
            continue

        if actual_hash.lower() != expected_hash.lower():
            mismatched.append(
                (expected_rel, expected_hash.lower(), actual_hash.lower())
            )

    write_report(
        report_path=report_path,
        base_dir=base_dir,
        manifest_count=len(manifest),
        actual_count=len(actual_files),
        missing=missing,
        mismatched=mismatched,
        extra=extra,
        read_errors=read_errors,
    )

    total_errors = (
        len(missing)
        + len(mismatched)
        + len(extra)
        + len(read_errors)
    )

    print()
    if total_errors == 0:
        print("[PASS] 所有文件均与目标版本一致。")
        print(f"报告：{report_path}")

        show_message(
            "CastleReforge 文件校验通过",
            f"所有文件均与目标版本一致。\n\n报告：{REPORT_NAME}",
            False,
        )
        return 0

    print("[FAIL] 文件版本校验失败。")
    print(f"缺失：{len(missing)}")
    print(f"SHA256 不符：{len(mismatched)}")
    print(f"多余：{len(extra)}")
    print(f"读取失败：{len(read_errors)}")
    print(f"详细报告：{report_path}")

    show_message(
        "CastleReforge 文件校验失败",
        "检测到文件缺失、版本不符或未登记文件。\n\n"
        f"详细信息已保存到：{REPORT_NAME}",
        True,
    )
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
