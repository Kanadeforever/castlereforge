def _png_chunk(t: bytes, data: bytes)->bytes:
    # 把 `struct.pack(">I",len(data))+t+data+struct.pack(">I",binascii.crc32(t+data)&0xffffffff)` 作为本函数结果交回调用者；执行到这里后本次函数调用结束。
    return struct.pack(">I",len(data))+t+data+struct.pack(">I",binascii.crc32(t+data)&0xffffffff)


# 定义函数 `write_png_rgba`。调用它时会从这里进入，参数在括号中传入，函数体按下面缩进顺序执行。
def write_png_rgba(path:Path,w:int,h:int,pixels:List[Tuple[int,int,int,int]])->None:
    # 检查条件 `len(pixels)!=w*h`；条件成立才执行下一层缩进代码，不成立就跳过这一分支。
    if len(pixels)!=w*h: raise ValueError("PNG 像素数不匹配")
    # 把右侧 `bytearray()` 计算得到的值保存到 `raw`，后面的判断或输出会继续使用它。
    raw=bytearray()
    # 开始循环 `y in range(h)`；每轮取一个元素放进循环变量，再执行下面的缩进代码。
    for y in range(h):
        # 把这一条新结果追加到列表 `raw`；不会覆盖前面已经收集的记录。
        raw.append(0)
        # 开始循环 `r,g,b,a in pixels[y*w:(y+1)*w]`；每轮取一个元素放进循环变量，再执行下面的缩进代码。
        for r,g,b,a in pixels[y*w:(y+1)*w]:raw.extend((r,g,b,a))
    # 把右侧 `b"\x89PNG\r\n\x1a\n"+_png_chunk(b"IHDR",struct.pack(">IIBBBBB",w,h,8,6,0,0…` 计算得到的值保存到 `png`，后面的判断或输出会继续使用它。
    png=b"\x89PNG\r\n\x1a\n"+_png_chunk(b"IHDR",struct.pack(">IIBBBBB",w,h,8,6,0,0,0))+_png_chunk(b"IDAT",zlib.compress(bytes(raw),9))+_png_chunk(b"IEND",b"")
    # 执行一次赋值：把 `True,exist_ok=True); path.write_bytes(png)` 的结果放入左侧 `path.parent.mkdir(parents` 对应的变量/字段。
    path.parent.mkdir(parents=True,exist_ok=True); path.write_bytes(png)


